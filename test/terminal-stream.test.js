test('stream filter retains split control state without releasing private payload', () => {
  const filter = new TerminalTextFilter()
  assert.equal(filter.feed('a\x1b]private'), 'a')
  assert.equal(filter.feed('x'.repeat(100000)), '')
  assert.equal(filter.feed('\x1b'), '')
  assert.equal(filter.feed('\\b\x1b[31'), 'b')
  assert.equal(filter.feed('m中文\r'), '中文\n')
  assert.equal(filter.feed('\n\ud83d'), '')
  assert.equal(filter.feed('\ude00'), '😀')
})
test('cursors reject cross-scope, changed sessions, tampering and restart', () => {
  const tokens = new StreamTokens(), token = tokens.encode('alice', 'stream1', 4)
  assert.equal(tokens.decode(token, 'alice', 'stream1'), 4)
  assert.throws(() => tokens.decode(token, 'bob', 'stream1'))
  assert.throws(() => tokens.decode(token, 'alice', 'stream2'), /session_changed/)
  assert.throws(() => tokens.decode(token + '0', 'alice', 'stream1'))
  assert.throws(() => new StreamTokens().decode(token, 'alice', 'stream1'))
})
test('buffer pagination does not split surrogate pairs or jump to tail', () => {
  const buffer = new IncrementalOutputBuffer(100)
  buffer.append('a😀b')
  assert.deepEqual(buffer.readSince(0, 2), { text: 'a', cursor: 1, truncated: false, hasMore: true })
  assert.equal(buffer.readSince(1, 2).text, '😀')
  buffer.append('x'.repeat(101))
  assert.equal(buffer.readSince(0, 10).truncated, true)
})
test('logs isolate scopes, preserve Unicode pages and restore sealed data', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tabby-logs-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const store = new TerminalLogStore(root), id = store.start('a', 'stream')
  store.append(id, '中文😀\n'); store.append(id, 'last\n')
  store.finish(id); await store.flush()
  const first = await store.read('a', id, 0, 2)
  assert.equal(first.text, '中文'); assert.equal(first.hasMore, true)
  assert.equal((await store.read('a', id, first.offset, 2)).text, '😀')
  await assert.rejects(store.read('b', id, 0, 100), /unavailable/)
  const restored = new TerminalLogStore(root)
  assert.equal((await restored.read('a', id, 0, 100)).text, '中文😀\nlast\n')
  assert.equal((await restored.list('a'))[0].status, 'sealed')
})
test('queue overflow is explicit and does not claim a complete log', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tabby-logs-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const store = new TerminalLogStore(root), id = store.start('a', 's')
  store.append(id, 'x'.repeat(1024 * 1024 + 1)); await store.flush()
  const result = await store.read('a', id, 0, 100)
  assert.equal(result.logState, 'partial'); assert.match(result.reason, /queue/)
})

test('fixed read boundary stays stable while logs grow and restart marks an open capture interrupted', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tabby-logs-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const store = new TerminalLogStore(root), id = store.start('a', 'stream')
  store.append(id, 'first'); await store.flush()
  const page = await store.read('a', id, 0, 2)
  store.append(id, '-later'); await store.flush()
  const rest = await store.read('a', id, page.offset, 100, page.readEnd)
  assert.equal(rest.text, 'rst'); assert.equal(rest.hasMore, false)
  const restored = new TerminalLogStore(root)
  assert.equal((await restored.read('a', id, 0, 100)).logState, 'interrupted')
})

test('full log capacity recovers expired sealed records without restarting or losing queued writes', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tabby-log-retention-'))
  const store = new TerminalLogStore(root)
  t.after(async () => { await store.flush(); fs.rmSync(root, { recursive: true, force: true }) })
  const now = Date.now()
  const clock = t.mock.method(Date, 'now', () => now)
  const expired = store.start('a', 'old')
  store.append(expired, 'old bytes'); store.finish(expired)
  const active = store.start('a', 'active')
  // Keep an old sealed log pinned by an in-flight read as retention elapses.
  const pinned = store.start('a', 'pinned')
  store.append(pinned, 'pinned'); store.finish(pinned)
  const reading = store.read('a', pinned, 0, 100).catch(() => undefined)
  for (let i = 3; i < 2000; i++) store.start('a', 'live-' + i)
  assert.throws(() => store.start('a', 'full'), /capacity/)
  clock.mock.mockImplementation(() => now + 8 * 86400000)
  const fresh = store.start('a', 'recovered')
  store.append(fresh, 'new bytes'); store.finish(fresh)
  assert.throws(() => store.start('a', 'full-again'), /capacity/)
  await store.flush(); await reading
  await assert.rejects(fs.promises.stat(path.join(root, expired + '.json')), { code: 'ENOENT' })
  assert.equal(fs.readdirSync(root).some(name => name.startsWith(expired)), false)
  assert.ok(fs.existsSync(path.join(root, active + '.json')), 'active logs must survive retention')
  assert.ok(fs.existsSync(path.join(root, pinned + '.json')), 'in-flight readers keep their log')
  assert.equal((await store.read('a', fresh, 0, 100)).text, 'new bytes')
  assert.equal(store.total, Buffer.byteLength('pinnednew bytes'), 'queued expired bytes must be deducted exactly once')
})
